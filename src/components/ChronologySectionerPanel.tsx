import { useCallback, useEffect, useState } from 'react';
import {
  AlertTriangle,
  ArrowRight,
  CalendarRange,
  CheckCircle2,
  Download,
  FileText,
  HelpCircle,
} from 'lucide-react';
import type { AttributionStatus, ChronologySection } from '../types.ts';

interface ChronologySectionerPanelProps {
  refreshTrigger: number;
}

const ATTRIBUTION_BADGE: Record<
  AttributionStatus,
  { label: string; classes: string; icon: 'ok' | 'warn' | 'help' }
> = {
  verified_strict: {
    label: 'Strict Attribution Verified',
    classes: 'border-emerald-200 bg-emerald-50 text-emerald-800',
    icon: 'ok',
  },
  inferred_needs_review: {
    label: 'Attribution Inferred (Review)',
    classes: 'border-amber-200 bg-amber-50 text-amber-800',
    icon: 'help',
  },
  ambiguous_warning: {
    label: 'Attribution Warning',
    classes: 'border-red-200 bg-red-50 text-red-800',
    icon: 'warn',
  },
};

const SEVERITY_BADGE: Record<number, string> = {
  1: 'border-slate-200 bg-slate-100 text-slate-700',
  2: 'border-amber-200 bg-amber-50 text-amber-800',
  3: 'border-orange-200 bg-orange-50 text-orange-800',
  4: 'border-red-200 bg-red-50 text-red-800',
};

export function ChronologySectionerPanel({ refreshTrigger }: ChronologySectionerPanelProps) {
  const [sectionBy, setSectionBy] = useState<'day' | 'month' | 'source' | 'framework'>('day');
  const [verifiedOnly, setVerifiedOnly] = useState(false);
  const [docCategory, setDocCategory] = useState('all');
  const [sections, setSections] = useState<ChronologySection[]>([]);
  const [totalEvents, setTotalEvents] = useState(0);
  const [undatedCount, setUndatedCount] = useState(0);
  const [loading, setLoading] = useState(false);

  const loadChronology = useCallback(async () => {
    setLoading(true);
    try {
      const params = new URLSearchParams();
      params.set('section_by', sectionBy);
      if (verifiedOnly) params.set('verified_only', 'true');
      if (docCategory !== 'all') params.set('document_category', docCategory);

      const res = await fetch(`/api/chronology?${params.toString()}`);
      if (res.ok) {
        const data = await res.json();
        setSections(data.sections || []);
        setTotalEvents(data.totalEvents || 0);
        setUndatedCount(data.undatedCount || 0);
      }
    } finally {
      setLoading(false);
    }
  }, [sectionBy, verifiedOnly, docCategory]);

  useEffect(() => {
    void loadChronology();
  }, [loadChronology, refreshTrigger]);

  function handleExportMarkdown() {
    const lines: string[] = [
      '# Forensic Event Chronology & Citations',
      '',
      '> **DISCLAIMER (EDUCATIONAL & PERSONAL USE ONLY):** This export was generated by a personal/educational documentation tool based on published peer-reviewed scientific articles and the DAIP Duluth Model Power & Control Wheels. It does **not** constitute legal advice, medical/psychological diagnosis, or an expert forensic opinion. Automated flags, OCR text, PII redactions, and sender/receiver attributions are screening aids only and must be independently verified by a human against original records. Provided **"AS IS"** without warranty or liability.',
      '',
      `Sectioned by: ${sectionBy} | Verified only: ${verifiedOnly} | Total events: ${totalEvents}`,
      '',
    ];

    for (const sec of sections) {
      lines.push(`## ${sec.title} (${sec.event_count} events)`);
      lines.push(`Sources: ${sec.source_files.join(', ')}`);
      lines.push('');

      for (const ev of sec.events) {
        const tsStr = ev.timestamp ? new Date(ev.timestamp).toUTCString() : 'Undated';
        lines.push(`### [${tsStr}] Severity ${ev.severity_score} — ${ev.sender} -> ${ev.receiver}`);
        lines.push(`- **Citation:** ${ev.placement_citation.citation_label}`);
        lines.push(
          `- **Attribution Check (${ev.attribution_audit.status}):** ${ev.attribution_audit.notes}`
        );
        lines.push(
          `- **Tactics:** ${ev.all_flags.map((f) => `${f.wheel}: ${f.category}`).join('; ')}`
        );
        lines.push(`- **Content (Sanitized=${ev.pii_redacted_count} PII masked):**`);
        lines.push('');
        lines.push(`> ${ev.content.replace(/\n/g, '\n> ')}`);
        lines.push('');
      }
    }

    const blob = new Blob([lines.join('\n')], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `chronology_${sectionBy}.md`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  }

  return (
    <div className="space-y-5">
      <div className="rounded-lg border border-slate-200 bg-white p-5 shadow-xs">
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <h2 className="text-lg font-semibold text-slate-900">
              Event Sectioner &amp; Multi-Source Chronology
            </h2>
            <p className="mt-1 text-sm text-slate-600">
              Cross-references events extracted from all uploaded evidence files, ordered chronologically and tagged with exact file, SHA-256 prefix, page/row/line/OCR placement citations, and sender/receiver attribution verification.
            </p>
          </div>

          <button
            type="button"
            disabled={sections.length === 0}
            onClick={handleExportMarkdown}
            className="inline-flex items-center gap-1.5 rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-100 disabled:opacity-40"
          >
            <Download className="h-3.5 w-3.5" />
            Export Chronology (.md)
          </button>
        </div>

        <div className="mt-4 grid gap-3 sm:grid-cols-4">
          <div>
            <label className="block text-xs font-medium text-slate-600">Section By</label>
            <select
              value={sectionBy}
              onChange={(e) =>
                setSectionBy(e.target.value as 'day' | 'month' | 'source' | 'framework')
              }
              className="mt-1 block w-full rounded-md border border-slate-300 bg-white px-2.5 py-1.5 text-sm text-slate-800"
            >
              <option value="day">Chronological Date (Day)</option>
              <option value="month">Chronological Month</option>
              <option value="source">Document Category</option>
              <option value="framework">Primary Abuse Framework</option>
            </select>
          </div>

          <div>
            <label className="block text-xs font-medium text-slate-600">Document Category</label>
            <select
              value={docCategory}
              onChange={(e) => setDocCategory(e.target.value)}
              className="mt-1 block w-full rounded-md border border-slate-300 bg-white px-2.5 py-1.5 text-sm text-slate-800"
            >
              <option value="all">All Document Types</option>
              <option value="email">Emails (.eml)</option>
              <option value="court_document">Court Documents</option>
              <option value="medical_document">Medical Documents</option>
              <option value="personal_communication">Personal Communications</option>
              <option value="spreadsheet_log">Spreadsheet Logs (.csv)</option>
              <option value="screenshot_ocr">OCR Screenshots</option>
              <option value="generic_document">General Documents</option>
            </select>
          </div>

          <div className="flex items-end pb-1">
            <label className="inline-flex items-center gap-2 text-xs font-medium text-slate-700 cursor-pointer">
              <input
                type="checkbox"
                checked={verifiedOnly}
                onChange={(e) => setVerifiedOnly(e.target.checked)}
                className="h-4 w-4 rounded border-slate-300"
              />
              Verified Events Only
            </label>
          </div>

          <div className="flex items-end justify-end text-xs text-slate-500 pb-1">
            <span>
              {sections.length} {sections.length === 1 ? 'section' : 'sections'} &middot;{' '}
              {totalEvents} {totalEvents === 1 ? 'event' : 'events'}
              {undatedCount > 0 ? ` (${undatedCount} undated)` : ''}
            </span>
          </div>
        </div>
      </div>

      {loading ? (
        <div className="rounded-lg border border-slate-200 bg-white p-10 text-center text-sm text-slate-500">
          Building chronology sections...
        </div>
      ) : sections.length === 0 ? (
        <div className="rounded-lg border border-slate-200 bg-white p-10 text-center text-sm text-slate-500">
          No flagged events available for chronology. Upload evidence files first or adjust filters.
        </div>
      ) : (
        <div className="space-y-5">
          {sections.map((section) => (
            <section
              key={section.section_id}
              className="rounded-lg border border-slate-200 bg-white shadow-xs overflow-hidden"
            >
              <header className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 bg-slate-50 px-5 py-3">
                <div className="flex items-center gap-2.5">
                  <CalendarRange className="h-4 w-4 text-slate-700" />
                  <div>
                    <h3 className="text-sm font-semibold text-slate-900">{section.title}</h3>
                    <p className="text-xs text-slate-500">
                      {section.subtitle} &middot; Sources: {section.source_files.join(', ')}
                    </p>
                  </div>
                </div>
                <div className="flex items-center gap-2 text-xs">
                  <span className="rounded border border-slate-200 bg-white px-2.5 py-0.5 font-medium text-slate-700">
                    {section.event_count} {section.event_count === 1 ? 'event' : 'events'}
                  </span>
                  <span
                    className={`rounded border px-2.5 py-0.5 font-medium ${
                      SEVERITY_BADGE[section.highest_severity] || SEVERITY_BADGE[1]
                    }`}
                  >
                    Peak Severity {section.highest_severity}
                  </span>
                </div>
              </header>

              <div className="divide-y divide-slate-200">
                {section.events.map((ev) => {
                  const attrCfg =
                    ATTRIBUTION_BADGE[ev.attribution_audit.status] ||
                    ATTRIBUTION_BADGE.inferred_needs_review;
                  return (
                    <div key={ev.id} className="p-5 space-y-2.5">
                      <div className="flex flex-wrap items-center justify-between gap-2">
                        <div className="flex flex-wrap items-center gap-2 text-xs">
                          <span className="font-semibold text-slate-900">
                            {ev.timestamp
                              ? new Date(ev.timestamp).toUTCString()
                              : 'Timestamp Pending'}
                          </span>
                          <span
                            className={`rounded border px-2 py-0.5 font-medium ${
                              SEVERITY_BADGE[ev.severity_score] || SEVERITY_BADGE[1]
                            }`}
                          >
                            Severity {ev.severity_score}
                          </span>
                          {ev.is_verified && (
                            <span className="rounded border border-emerald-300 bg-emerald-50 px-2 py-0.5 font-medium text-emerald-800">
                              Human Verified
                            </span>
                          )}
                        </div>

                        <span className="inline-flex items-center gap-1.5 rounded border border-slate-200 bg-slate-100 px-2.5 py-1 font-mono text-xs text-slate-700">
                          <FileText className="h-3.5 w-3.5 text-slate-600 shrink-0" />
                          {ev.placement_citation.citation_label}
                        </span>
                      </div>

                      <div className="flex flex-wrap items-center gap-2 text-xs">
                        <span className="inline-flex items-center gap-1.5 rounded bg-slate-100 px-2.5 py-1 font-medium text-slate-800">
                          <span>From: {ev.sender}</span>
                          <ArrowRight className="h-3 w-3 text-slate-500" />
                          <span>To: {ev.receiver}</span>
                        </span>

                        <span
                          className={`inline-flex items-center gap-1 rounded border px-2 py-1 font-medium ${attrCfg.classes}`}
                          title={ev.attribution_audit.notes}
                        >
                          {attrCfg.icon === 'ok' && <CheckCircle2 className="h-3 w-3" />}
                          {attrCfg.icon === 'help' && <HelpCircle className="h-3 w-3" />}
                          {attrCfg.icon === 'warn' && <AlertTriangle className="h-3 w-3" />}
                          {attrCfg.label}
                        </span>

                        {ev.pii_redacted_count > 0 && (
                          <span className="rounded border border-slate-200 bg-white px-2 py-1 text-slate-600">
                            {ev.pii_redacted_count} PII redacted
                          </span>
                        )}
                      </div>

                      <div className="rounded-md border border-slate-200 bg-slate-50 p-3 text-sm text-slate-800 whitespace-pre-wrap">
                        {ev.content}
                      </div>

                      <div className="text-xs text-slate-500">
                        <span className="font-medium text-slate-700">Attribution Check:</span>{' '}
                        {ev.attribution_audit.notes}
                      </div>

                      {ev.all_flags.length > 0 && (
                        <div className="flex flex-wrap gap-1.5">
                          {ev.all_flags.map((f, idx) => (
                            <span
                              key={idx}
                              className="rounded border border-slate-200 bg-white px-2 py-0.5 text-xs text-slate-700"
                            >
                              <span className="font-medium">{f.wheel}:</span> {f.category}
                            </span>
                          ))}
                        </div>
                      )}
                    </div>
                  );
                })}
              </div>
            </section>
          ))}
        </div>
      )}
    </div>
  );
}
